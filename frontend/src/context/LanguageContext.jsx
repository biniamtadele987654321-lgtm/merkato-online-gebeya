const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    const saved = localStorage.getItem('merkato-language');
    return translations[saved] ? saved : 'en';
  });

  useEffect(() => {
    const definition = languages.find((entry) => entry.code === language);
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.dataset.language = language;
    document.title = `${definition.native === 'English' ? 'Merkato Online Gebeya' : 'መርካቶ ኦንላይን ገበያ'} — ${translations[language].ethiopianMarket}`;
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage(nextLanguage) {
      if (!translations[nextLanguage]) return;
      localStorage.setItem('merkato-language', nextLanguage);
      setLanguage(nextLanguage);
    },
    t(key) {
      return translations[language][key] || translations.en[key] || key;
    },
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}

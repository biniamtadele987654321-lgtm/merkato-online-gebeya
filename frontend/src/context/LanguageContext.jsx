export function categoryTranslationKey(category) {
  if (typeof category !== 'string') return '';
  const match = Object.keys(categoryTranslationKeys).find(
    (name) => name.toLocaleLowerCase() === category.toLocaleLowerCase(),
  );
  return categoryTranslationKeys[match] || category;
}

